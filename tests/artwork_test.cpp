// Reads the pixel dimensions out of a JPEG's first SOF marker. Small enough to
// justify itself: the alternative is an image library dependency dragged in for
// one assertion, and "artwork is 16:9 at kArtworkWidth" is a promise the header
// makes that nothing else here would check.
struct JpegSize {
    int width = 0;
    int height = 0;
};

std::optional<JpegSize> ReadJpegSize(const fs::path& path) {
    std::ifstream in(path, std::ios::binary);
    if (!in) return std::nullopt;

    std::vector<unsigned char> bytes((std::istreambuf_iterator<char>(in)),
                                      std::istreambuf_iterator<char>());
    if (bytes.size() < 4 || bytes[0] != 0xFF || bytes[1] != 0xD8) return std::nullopt;  // not SOI

    for (size_t i = 2; i + 9 < bytes.size();) {
        if (bytes[i] != 0xFF) return std::nullopt;
        const unsigned char marker = bytes[i + 1];
        const size_t length = (static_cast<size_t>(bytes[i + 2]) << 8) | bytes[i + 3];

        // SOFn carries the dimensions. C4/C8/CC are DHT/JPG/DAC, not SOF.
        const bool is_sof = marker >= 0xC0 && marker <= 0xCF && marker != 0xC4 &&
                            marker != 0xC8 && marker != 0xCC;
        if (is_sof) {
            JpegSize size;
            size.height = (static_cast<int>(bytes[i + 5]) << 8) | bytes[i + 6];
            size.width = (static_cast<int>(bytes[i + 7]) << 8) | bytes[i + 8];
            return size;
        }
        i += 2 + length;
    }
    return std::nullopt;
}

MediaEntry EntryFor(const fs::path& path) {
    MediaEntry entry;
    entry.path = path;
    return entry;
}

