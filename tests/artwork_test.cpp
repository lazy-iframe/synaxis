// The key hashes the path, not the parsed title: a title is a parser guess, and
// keying on it would strand every cached tile whenever the parser improves.
TEST_F(ArtworkTest, CacheKeyIgnoresMetadata) {
    ArtworkCache cache({}, dir_ / "cache");

    MediaEntry bare = EntryFor("/media/film.mkv");
    MediaEntry annotated = EntryFor("/media/film.mkv");
    annotated.metadata.title = "Something The Parser Learned Later";
    annotated.metadata.year = 2021;

    EXPECT_EQ(cache.PathFor(bare, "frame"), cache.PathFor(annotated, "frame"));
}

