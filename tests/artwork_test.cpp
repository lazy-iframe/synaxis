// A miss is remembered briefly, so an unmatched library doesn't re-query every
// provider on every launch.
TEST_F(ArtworkTest, MissIsRememberedAndProviderIsNotImmediatelyRetried) {
    auto provider = std::make_unique<StubProvider>("stub", /*succeeds=*/false);
    StubProvider* raw = provider.get();

    std::vector<std::unique_ptr<ArtworkProvider>> providers;
    providers.push_back(std::move(provider));
    ArtworkCache cache(std::move(providers), dir_ / "cache");

    const MediaEntry entry = EntryFor("/media/film.mkv");
    EXPECT_FALSE(cache.Get(entry).has_value());
    EXPECT_FALSE(cache.Get(entry).has_value());
    EXPECT_EQ(raw->calls, 1) << "a fresh miss should not be re-fetched";
}

// ...but only briefly. "No match" is a fact about TMDB's catalogue on one
// afternoon, not about the file, so an aged marker must let the provider try
// again — otherwise a transient outage would blank those tiles permanently.
TEST_F(ArtworkTest, StaleMissIsRetried) {
    auto provider = std::make_unique<StubProvider>("stub", /*succeeds=*/false);
    StubProvider* raw = provider.get();

    std::vector<std::unique_ptr<ArtworkProvider>> providers;
    providers.push_back(std::move(provider));
    ArtworkCache cache(std::move(providers), dir_ / "cache");

    const MediaEntry entry = EntryFor("/media/film.mkv");
    ASSERT_FALSE(cache.Get(entry).has_value());
    ASSERT_EQ(raw->calls, 1);

    // Backdate the marker past the retry window.
    const fs::path marker = cache.PathForMiss(entry, "stub");
    ASSERT_TRUE(fs::exists(marker));
    fs::last_write_time(marker, fs::file_time_type::clock::now() -
                                    std::chrono::hours(24 * (ArtworkCache::kMissRetryDays + 1)));

    EXPECT_FALSE(cache.Get(entry).has_value());
    EXPECT_EQ(raw->calls, 2) << "a stale miss should be retried";
}

// The regression that motivated keying the cache by provider.
//
// A tile cached by a lower-priority provider must not lock a better one out
// forever: configure a TMDB key after browsing once, and every existing frame
// tile has to be upgradable. Keyed on the file alone, "better" never gets asked.
TEST_F(ArtworkTest, BetterProviderSupersedesAlreadyCachedWorseOne) {
    const MediaEntry entry = EntryFor("/media/film.mkv");
    const fs::path cache_dir = dir_ / "cache";

    // First run: only the fallback exists, so it produces the tile.
    {
        std::vector<std::unique_ptr<ArtworkProvider>> providers;
        providers.push_back(std::make_unique<StubProvider>("frame", /*succeeds=*/true, 64));
        ArtworkCache cache(std::move(providers), cache_dir);
        ASSERT_TRUE(cache.Get(entry).has_value());
    }

    // Second run: a better provider is configured and must win, even though the
    // fallback's tile is sitting in the cache.
    {
        auto better = std::make_unique<StubProvider>("tmdb", /*succeeds=*/true, 128);
        StubProvider* better_raw = better.get();

        std::vector<std::unique_ptr<ArtworkProvider>> providers;
        providers.push_back(std::move(better));
        providers.push_back(std::make_unique<StubProvider>("frame", /*succeeds=*/true, 64));
        ArtworkCache cache(std::move(providers), cache_dir);

        std::optional<fs::path> art = cache.Get(entry);
        ASSERT_TRUE(art.has_value());
        EXPECT_EQ(better_raw->calls, 1) << "the better provider was never consulted";
        EXPECT_EQ(fs::file_size(*art), 128u) << "the stale fallback tile was served instead";
    }
}

// The flip side: once the better provider has cached a tile, the fallback must
// not be consulted at all.
TEST_F(ArtworkTest, CachedBetterProviderShortCircuitsFallback) {
    const MediaEntry entry = EntryFor("/media/film.mkv");
    const fs::path cache_dir = dir_ / "cache";

    {
        std::vector<std::unique_ptr<ArtworkProvider>> providers;
        providers.push_back(std::make_unique<StubProvider>("tmdb", /*succeeds=*/true, 128));
        ArtworkCache cache(std::move(providers), cache_dir);
        ASSERT_TRUE(cache.Get(entry).has_value());
    }
    {
        auto fallback = std::make_unique<StubProvider>("frame", /*succeeds=*/true, 64);
        StubProvider* fallback_raw = fallback.get();

        std::vector<std::unique_ptr<ArtworkProvider>> providers;
        providers.push_back(std::make_unique<StubProvider>("tmdb", /*succeeds=*/true, 128));
        providers.push_back(std::move(fallback));
        ArtworkCache cache(std::move(providers), cache_dir);

        ASSERT_TRUE(cache.Get(entry).has_value());
        EXPECT_EQ(fallback_raw->calls, 0);
    }
}

// Cached() answers from disk alone: a UI thread uses it to decide what to paint
// and must never trigger a fetch by asking.
TEST_F(ArtworkTest, CachedReadsWithoutFetching) {
    auto provider = std::make_unique<StubProvider>("stub", /*succeeds=*/true);
    StubProvider* raw = provider.get();

    std::vector<std::unique_ptr<ArtworkProvider>> providers;
    providers.push_back(std::move(provider));
    ArtworkCache cache(std::move(providers), dir_ / "cache");

    const MediaEntry entry = EntryFor("/media/film.mkv");
    EXPECT_FALSE(cache.Cached(entry).has_value());
    EXPECT_EQ(raw->calls, 0) << "Cached() must not fetch";

    ASSERT_TRUE(cache.Get(entry).has_value());
    EXPECT_EQ(cache.Cached(entry), cache.Get(entry));
}

// Cached() returns the best available, not merely the first found on disk.
TEST_F(ArtworkTest, CachedPrefersBetterProvider) {
    const MediaEntry entry = EntryFor("/media/film.mkv");
    const fs::path cache_dir = dir_ / "cache";

    std::vector<std::unique_ptr<ArtworkProvider>> providers;
    providers.push_back(std::make_unique<StubProvider>("tmdb", /*succeeds=*/true, 128));
    providers.push_back(std::make_unique<StubProvider>("frame", /*succeeds=*/true, 64));
    ArtworkCache cache(std::move(providers), cache_dir);

    // Both tiles on disk; the chain must report the higher-priority one.
    fs::create_directories(cache_dir);
    { std::ofstream(cache.PathFor(entry, "frame")) << std::string(64, 'x'); }
    { std::ofstream(cache.PathFor(entry, "tmdb")) << std::string(128, 'x'); }

    std::optional<fs::path> art = cache.Cached(entry);
    ASSERT_TRUE(art.has_value());
    EXPECT_EQ(fs::file_size(*art), 128u);
}

